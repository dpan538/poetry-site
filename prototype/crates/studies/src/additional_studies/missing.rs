fn cup(p: &mut Painting, [x, y]: Point, scale: f32, glaze: u32) {
    let q = |u, v| [x + u * scale, y + v * scale];
    p.glow(
        q(0.033, 0.01),
        [0.129 * scale, 0.044 * scale],
        0x916677,
        0.65,
    );
    p.oval(q(0., 0.), [0.095 * scale, 0.029 * scale], 0xFFF1CC);
    p.oval(q(0., -0.004), [0.081 * scale, 0.020 * scale], 0xD8BAB3);
    p.oval(q(0.056, -0.038), [0.028 * scale, 0.024 * scale], 0xF6DDC4);
    p.oval(q(0.058, -0.039), [0.015 * scale, 0.014 * scale], 0xB48279);
    p.polygon(
        &[
            q(-0.056, -0.061),
            q(0.054, -0.063),
            q(0.040, -0.017),
            q(0.018, 0.001),
            q(-0.024, 0.001),
            q(-0.044, -0.018),
        ],
        glaze,
    );
    p.line(
        q(-0.044, -0.046),
        q(-0.031, -0.016),
        0.004 * scale,
        0xFFF0D0,
    );
    p.oval(q(0., -0.061), [0.055 * scale, 0.017 * scale], 0xF2DCC6);
    p.oval(q(0., -0.062), [0.044 * scale, 0.010 * scale], 0xA47466);
}

pub(super) fn light(p: &mut Painting, t: f32) {
    // The sheer fabric is fastened at its header. The fold swings aside
    // under the draft and comes back slowly; its hem carries the most motion.
    let gust = smooth(1.35, 5.25, t) * (1. - 0.43 * smooth(8.1, 13.7, t));
    p.wash(|[x, y], c| {
        if !(0.113..0.604).contains(&y) || !(0.405..0.69).contains(&x) {
            return c;
        }
        let h = (y - 0.113) / 0.491;
        let left = 0.447 - 0.078 * gust * h.powf(1.35) + 0.012 * (y * 17. - t * 1.14).sin() * h;
        let right =
            0.554 + 0.122 * h - 0.171 * gust * h.powf(1.36) + 0.013 * (y * 20. - t * 1.4).sin() * h;
        let hem = 0.585 + 0.016 * ((x - left) * 20. - t * 0.94).sin();
        let coverage = smooth(left - 0.009, left + 0.007, x)
            * (1. - smooth(right - 0.008, right + 0.010, x))
            * (1. - smooth(hem - 0.009, hem, y));
        let fold = ((x - left) / (right - left).max(0.010) * 26.).sin() * 0.20 + 0.68;
        mix(c, tint(0xF8D6CD), coverage * fold)
    });
    flowers(p);
    for i in 0..23 {
        let age = (t - 0.074 * i as f32).max(0.);
        let drift = i as f32 / 23.;
        let opacity = (1. - smooth(4., 11.6, t))
            * smooth(0.15, 1.3, i as f32)
            * (1. - smooth(0.47, 1., drift))
            * 0.38;
        let x = 0.351 + 0.072 * drift.powi(2) + (age * 2.3 - 4. * drift).sin() * 0.016 * drift;
        let y = 0.748 - 0.154 * drift;
        p.glow(
            [x, y],
            [0.009 + 0.021 * drift, 0.010 + 0.015 * drift],
            0xFFE5C8,
            opacity,
        );
    }
}
